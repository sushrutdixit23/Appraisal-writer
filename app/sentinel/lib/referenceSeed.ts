// Sentinel - turning verified filings into the shared reference peer set. Every statement goes through the same reader
// and the same validation a person's own import does (balance sheet must balance, identities must hold), so a figure
// that would be refused on the Import page cannot reach the reference set either. The SQL is idempotent: a company
// that already exists under that name (anyone's) is left alone, and a period that already exists is skipped.

import { autofillFromSheet, parseCsv } from "./autofill/sheet";
import { applyAutofillPeriod } from "./autofill/apply";
import { OPTIONAL_COLUMNS, OPTIONAL_TEXT_COLUMNS } from "./fields";
import { normaliseUnit } from "./units";
import { prepareFromForm, type StatementRow } from "./validate";

export type SeedEntry = { company_name: string; sector: string; industry: string; unit: string; basis: "standalone" | "consolidated"; csv: string; source: string };
export type SeedCompany = { entry: SeedEntry; rows: StatementRow[] };

/** Read and validate one company's CSV; throws with the reason if any period would be refused. */
export function buildSeedCompany(entry: SeedEntry, csvText: string): SeedCompany {
  const unit = normaliseUnit(entry.unit);
  if (!unit) throw new Error(`${entry.company_name}: unit "${entry.unit}" is not recognised.`);
  const result = autofillFromSheet(parseCsv(csvText), { kind: "csv", preferredBasis: entry.basis, sourceFile: entry.csv });
  const rows: StatementRow[] = [];
  for (const period of result.periods) {
    const applied = applyAutofillPeriod(period, unit, unit);
    const prepared = prepareFromForm(
      {
        periodType: period.period_type ?? "", periodLabel: period.period_label ?? "", periodEndDate: period.period_end_date ?? "",
        basis: period.basis ?? entry.basis, values: applied.values, sourceFile: "reference-universe seed",
        extractionNotes: `Hand-verified against the filing. ${entry.source}`,
      },
      []
    );
    if (!prepared.row) throw new Error(`${entry.company_name} ${period.period_label}: ${prepared.errors.join("; ")}`);
    if (prepared.errors.length > 0) throw new Error(`${entry.company_name} ${period.period_label}: ${prepared.errors.join("; ")}`);
    rows.push(prepared.row);
  }
  return { entry, rows };
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lit = (v: unknown) => (typeof v === "number" ? String(v) : q(String(v)));
const OPTIONAL = new Set<string>([...OPTIONAL_COLUMNS, ...OPTIONAL_TEXT_COLUMNS]);

export function seedSql(companies: SeedCompany[]): string {
  const out = [
    "-- Reference peer set: hand-verified filings, read and validated by the app's own import rules.",
    "-- Generated by scripts/seed-reference-universe.ts from data/reference-universe/. NOT APPLIED: run it in the",
    "-- Supabase SQL editor (safe to run twice). A company already present under the same name is left alone, and so",
    "-- is a period already on file, so running it on a project that has its own copy of these companies adds nothing.",
    "",
  ];
  for (const { entry, rows } of companies) {
    const name = q(entry.company_name);
    out.push(
      `insert into sentinel_workspaces (owner_id, company_name, sector, industry, is_public_reference, fiscal_year_start_month, currency, currency_unit, comparison_basis)`,
      `select null, ${name}, ${q(entry.sector)}, ${q(entry.industry)}, true, 4, 'INR', ${q(normaliseUnit(entry.unit)!)}, ${q(entry.basis)}`,
      `where not exists (select 1 from sentinel_workspaces where lower(company_name) = lower(${name}));`,
      ""
    );
    for (const row of rows) {
      const record = Object.entries(row).filter(([k, v]) => v !== null && v !== undefined && !(OPTIONAL.has(k) && v === null));
      const cols = ["workspace_id", ...record.map(([k]) => k)];
      const vals = ["w.id", ...record.map(([, v]) => lit(v))];
      out.push(
        `insert into sentinel_statements (${cols.join(", ")})`,
        `select ${vals.join(", ")} from sentinel_workspaces w`,
        `where w.is_public_reference and lower(w.company_name) = lower(${name})`,
        `on conflict do nothing;`,
        ""
      );
    }
  }
  return out.join("\n");
}
